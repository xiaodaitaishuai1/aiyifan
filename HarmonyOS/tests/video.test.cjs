const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('D:/DevEco Studio/tools/hvigor/hvigor-ohos-plugin/node_modules/typescript');
const Module = require('node:module');
const path = require('node:path');
const sourcePath = path.resolve(__dirname, '../entry/src/main/ets/common/network/VideoCatalog.ts');
const mod = new Module(sourcePath, module);
mod.filename = sourcePath;
mod.paths = module.paths;
mod._compile(ts.transpileModule(fs.readFileSync(sourcePath, 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText, sourcePath);
const {parseDetail, parsePlayback} = mod.exports;
const detail = parseDetail(JSON.stringify({data:{detailInfo:{mediaKey:'v',title:'剧',videoType:1,episodes:[{episodeKey:'e',episodeId:42,episodeTitle:'第1集'},null,{episodeKey:''}]}}}), 'v');
assert.equal(detail.episodes.length,1);
assert.equal(detail.episodes[0].uniqueId,42);
assert.throws(()=>parseDetail('{}','v'));
assert.throws(()=>parseDetail(JSON.stringify({data:{detailInfo:{mediaKey:'other',title:'剧'}}}),'v'));
const variants = [{resolution:'720',mediaUrl:'https://example.com/a.m3u8'}, {resolution:'1080',mediaUrl:'https://example.com/b.m3u8',isDefault:true}];
assert.equal(parsePlayback(JSON.stringify({data:{list:variants}}),'').mediaUrl,variants[1].mediaUrl);
assert.equal(parsePlayback(JSON.stringify({data:{list:variants}}),'720').mediaUrl,variants[0].mediaUrl);
assert.throws(()=>parsePlayback('{"data":{"list":[]}}',''));
console.log('PASS: detail identities, episode IDs, playback selection and malformed responses');
