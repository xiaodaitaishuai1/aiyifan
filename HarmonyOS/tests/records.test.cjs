const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('D:/DevEco Studio/tools/hvigor/hvigor-ohos-plugin/node_modules/typescript');
const Module = require('node:module');
const path = require('node:path');
const sourcePath = path.resolve(__dirname, '../entry/src/main/ets/common/storage/RecordPolicy.ts');
const mod = new Module(sourcePath, module);
mod.filename = sourcePath;
mod.paths = module.paths;
mod._compile(ts.transpileModule(fs.readFileSync(sourcePath, 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText, sourcePath);
const {upsertRecord,toggleFavorite,resumePosition}=mod.exports;
const a={mediaKey:'a',title:'A',coverUrl:'',episodeKey:'e',position:30,duration:100,updatedAt:1};
assert.equal(upsertRecord([a],{...a,position:40})[0].position,40);
assert.equal(upsertRecord([a],a).length,1);
assert.equal(toggleFavorite([a],a).length,0);
assert.equal(toggleFavorite([],a).length,1);
assert.equal(resumePosition(a,'e'),30);
assert.equal(resumePosition(a,'other'),0);
assert.equal(resumePosition({...a,position:100},'e'),0);
console.log('PASS: history replacement, favorites toggle, episode-specific resume and completed playback');
