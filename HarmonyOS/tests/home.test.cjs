const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('D:/DevEco Studio/tools/hvigor/hvigor-ohos-plugin/node_modules/typescript');
const Module = require('node:module');
const path = require('node:path');
const sourcePath = path.resolve(__dirname, '../entry/src/main/ets/common/network/HomeCatalog.ts');
const mod = new Module(sourcePath, module);
mod.filename = sourcePath;
mod.paths = module.paths;
mod._compile(ts.transpileModule(fs.readFileSync(sourcePath, 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText, sourcePath);
const { parseHome, searchCatalog, normalizeApi } = mod.exports;
const input = {data:{list:[{name:'电影',list:[{mediaKey:'a',title:'测试电影',coverImgUrl:'https://img/a',videoType:1},{mediaKey:'a',title:'重复'},{mediaKey:'ad',videoType:3},{title:'无标识'},null]}]}};
const sections = parseHome(JSON.stringify(input));
assert.equal(sections.length, 1);
assert.equal(sections[0].videos.length, 1);
assert.equal(sections[0].videos[0].coverUrl, 'https://img/a');
assert.equal(searchCatalog(sections,'测试').length,1);
assert.equal(searchCatalog(sections,'不存在').length,0);
assert.equal(searchCatalog(sections,'  ').length,0);
assert.deepEqual(parseHome('{}'),[]);
assert.throws(()=>parseHome('{'));
assert.equal(normalizeApi(' https://example.com '), 'https://example.com/');
assert.equal(normalizeApi('javascript:alert(1)'), 'https://api.tripdata.app/');
console.log('PASS: home parsing, deduplication, filtering, empty/error data and API validation');
